/**
 * The customer facing links.
 *
 * A capability grant, not a login. The customer never has an account, the link
 * reaches exactly one record, and it expires. Seeding them means the customer
 * side of the product can actually be opened, which otherwise sits untested
 * behind a token nobody can mint by hand.
 */
async function portalLinks(
  sql: postgres.Sql,
  customers: Map<string, { customer: string; property: string }>,
): Promise<{ estimate: string; job: string }> {
  const grant = async (scope: string, customerKey: string, subjectId: string, days: number): Promise<string> => {
    const token = randomBytes(24).toString("base64url");
    const expires = new Date();
    expires.setDate(expires.getDate() + days);
    await sql`
      insert into public.portal_grant
        (id, organization_id, customer_id, scope, subject_id, token_hash, expires_at, max_uses)
      values (${randomUUID()}, ${ORG}, ${customers.get(customerKey)?.customer ?? null}, ${scope},
              ${subjectId}, ${createHash("sha256").update(token).digest("hex")}, ${expires}, null)
    `;
    return token;
  };

  return {
    estimate: await grant("estimate", "delgado", id("est:delgado"), 14),
    job: await grant("job", "delgado", id("job:delgado-replace"), 7),
  };
}

/**
 * A session the demo can actually sign in with.
 *
 * Printed once, at the end, and never stored anywhere else. The database holds
 * the hash, so re-running the seed produces a new token rather than recovering
 * the old one, which is the property you want from session storage.
 */
async function session(sql: postgres.Sql, userKey: string): Promise<string> {
  const token = randomBytes(32).toString("base64url");
  const hash = createHash("sha256").update(token).digest("hex");
  const expires = new Date();
  expires.setDate(expires.getDate() + 30);

  await sql`
    insert into public.session (id, user_id, token_hash, active_organization_id, expires_at)
    values (${randomUUID()}, ${id(`user:${userKey}`)}, ${hash}, ${ORG}, ${expires})
  `;
  return token;
}

