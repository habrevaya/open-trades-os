/**
 * THE DEMO COMPANY
 *
 * `pnpm db:seed` turns a migrated but empty database into a company with a
 * day's work in it: a dispatch board with real gaps, a technician's route, an
 * estimate waiting on a decision, invoices in three states, and a customer
 * portal link that opens.
 *
 * It exists for three audiences, and the order matters.
 *
 * A contractor evaluating this can see the board with work on it instead of
 * an empty state, which is the difference between "I could run my shop on
 * this" and "I cannot tell".
 *
 * A contributor gets something to develop against in one command. Building a
 * plausible day by hand through the UI takes half an hour, and everybody who
 * skips it ends up testing against one customer called "test test".
 *
 * And it is the fixture the product screenshots are taken from, which means
 * the screenshots are of the actual application rendering actual rows rather
 * than of a mockup. A marketing screenshot that cannot be regenerated by a
 * command is a promise nobody is checking.
 *
 * Every id is derived from a name rather than random, so re-running updates
 * the same company instead of accumulating a new one each time.
 *
 * It writes raw SQL rather than calling the service layer, and that is a
 * layering constraint rather than a shortcut: `api` depends on `db`, so a
 * seed here that called the services would close a cycle. It also means the
 * seed keeps working when a service is mid-refactor, which is exactly when
 * somebody wants a database with data in it.
 *
 * The cost is that this file has to be kept honest by hand. The enum values
 * and the foreign keys are checked by Postgres on every run, which has caught
 * three mistakes so far, but nothing here knows about a business rule the
 * service layer enforces.
 */

const URL = process.env.DATABASE_URL ?? "postgresql://opentradesos:opentradesos@localhost:5432/opentradesos";

/**
 * WHICH TRADE THE DEMO COMPANY IS IN
 *
 * `pnpm db:seed --pack electrical` seeds an electrical shop instead of an
 * HVAC one. The price book, the job types and the company's name come from
 * the pack, and the day's work does not: the jobs, customers and invoices
 * are written as HVAC and would be nonsense on an electrician's board.
 *
 * So a non default pack seeds the CATALOGUE ONLY and stops there. That is a
 * real screen rather than a compromise: the price book is the single most
 * trade specific thing in the product, it is the first thing a contractor
 * looks at to decide whether anybody understood their trade, and it comes
 * straight out of the pack with no fixtures in between.
 *
 * Writing a day's work for eight trades is the alternative and it is not a
 * better one: eight sets of invented job summaries, by somebody who has run
 * none of those trades, is how a demo starts lying.
 */
const PACK = (() => {
  const flag = process.argv.indexOf("--pack");
  return flag === -1 ? "hvac" : (process.argv[flag + 1] ?? "hvac");
})();
const CATALOGUE_ONLY = PACK !== "hvac";

/** Stable ids from names. Re-running the seed must not duplicate anything. */
function id(name: string): string {
  const h = createHash("sha256").update(`opentradesos:seed:${name}`).digest("hex");
  return [
    h.slice(0, 8), h.slice(8, 12), `4${h.slice(13, 16)}`,
    ((parseInt(h.slice(16, 17), 16) & 0x3) | 0x8).toString(16) + h.slice(17, 20),
    h.slice(20, 32),
  ].join("-");
}

