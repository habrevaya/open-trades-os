/**
 * THE DEMO COMPANY
 *
 * `pnpm db:seed` turns a migrated but empty database into a company with a
 * day's work in it: a dispatch board with real gaps, a technician's route, an
 * estimate waiting on a decision, invoices in three states, and a customer
 * portal link that opens.
 *
 * It exists for three audiences, and the order matters.
 *
 * A contractor evaluating this can see the board with work on it instead of
 * an empty state, which is the difference between "I could run my shop on
 * this" and "I cannot tell".
 *
 * A contributor gets something to develop against in one command. Building a
 * plausible day by hand through the UI takes half an hour, and everybody who
 * skips it ends up testing against one customer called "test test".
 *
 * And it is the fixture the product screenshots are taken from, which means
 * the screenshots are of the actual application rendering actual rows rather
 * than of a mockup. A marketing screenshot that cannot be regenerated by a
 * command is a promise nobody is checking.
 *
 * Every id is derived from a name rather than random, so re-running updates
 * the same company instead of accumulating a new one each time.
 */

const URL = process.env.DATABASE_URL ?? "postgresql://opentradesos:opentradesos@localhost:5432/opentradesos";

/** Stable ids from names. Re-running the seed must not duplicate anything. */
function id(name: string): string {
  const h = createHash("sha256").update(`opentradesos:seed:${name}`).digest("hex");
  return [
    h.slice(0, 8), h.slice(8, 12), `4${h.slice(13, 16)}`,
    ((parseInt(h.slice(16, 17), 16) & 0x3) | 0x8).toString(16) + h.slice(17, 20),
    h.slice(20, 32),
  ].join("-");
}

const ORG = id("org");

/**
 * The demo day is always today, and it is laid out around the current hour.
 *
 * Two mistakes are easy here and both make the board lie.
 *
 * Hardcoded dates show an empty board the day after the seed was written, and
 * somebody concludes the board is broken. Hardcoded HOURS are subtler: an
 * 8am-to-5pm day seeded at nine in the evening renders with every visit in the
 * past, so the dispatcher's "running late" badge reads four out of six and the
 * screen looks like a company in crisis rather than a company at work.
 *
 * So the day is built relative to now. The anchor is clamped into working
 * hours, because a day centred on 3am would run past midnight and split
 * across two dates, and the board is a single date.
 */
function anchor(): Date {
  const d = new Date();
  const hour = d.getHours();
  d.setHours(Math.min(17, Math.max(10, hour)), 0, 0, 0);
  return d;
}

/** Hours from the anchor, so the past is done and the future is scheduled. */
function at(hoursFromAnchor: number, dayOffset = 0): Date {
  const d = anchor();
  d.setDate(d.getDate() + dayOffset);
  d.setMinutes(d.getMinutes() + Math.round(hoursFromAnchor * 60));
  return d;
}

