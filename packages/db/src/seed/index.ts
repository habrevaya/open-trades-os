/**
 * The HVAC pack, applied the same way the setup wizard applies it.
 *
 * Seeding job types and a price book by hand here would let this file drift
 * from what a real company gets on day one, and the demo would slowly stop
 * demonstrating the product.
 */
async function tradePack(sql: postgres.Sql): Promise<Map<string, string>> {
  const { packById } = await import("@opentradesos/trade-packs");
  const pack = packById("hvac");
  if (!pack) throw new Error("The hvac trade pack is missing");

  const categories = new Map<string, string>();
  for (const item of pack.priceBook) {
    if (categories.has(item.category)) continue;
    const categoryId = id(`cat:${item.category}`);
    categories.set(item.category, categoryId);
    await sql`insert into public.price_book_category (id, organization_id, name, code)
              values (${categoryId}, ${ORG}, ${item.category}, ${item.category.toLowerCase().replace(/[^a-z0-9]+/g, "-")})`;
  }

  for (const item of pack.priceBook) {
    const itemId = id(`pb:${item.code}`);
    await sql`
      insert into public.price_book_item (id, organization_id, category_id, kind, code, trade_pack_id)
      values (${itemId}, ${ORG}, ${categories.get(item.category) ?? null}, ${item.kind}, ${item.code},
              ${`${pack.id}@${pack.version}`})
    `;
    await sql`
      insert into public.price_book_item_version
        (id, organization_id, item_id, version, name, description, price, cost, labor_minutes, taxable, tax_class, warranty_months, effective_from)
      values (${id(`pbv:${item.code}`)}, ${ORG}, ${itemId}, 1, ${item.name}, ${item.description ?? null},
              ${item.price}, ${item.cost ?? null}, ${item.laborMinutes ?? null}, ${item.taxable},
              ${item.taxClass ?? null}, ${item.warrantyMonths ?? null}, now())
    `;
  }

  const jobTypes = new Map<string, string>();
  for (const jobType of pack.jobTypes) {
    const jobTypeId = id(`jt:${jobType.code}`);
    await sql`
      insert into public.job_type (id, organization_id, name, code, capacity_model, default_duration_minutes, required_skills, color)
      values (${jobTypeId}, ${ORG}, ${jobType.name}, ${jobType.code}, ${jobType.capacityModel},
              ${jobType.defaultDurationMinutes}, ${JSON.stringify(jobType.requiredSkills)}, ${jobType.color ?? null})
    `;
    jobTypes.set(jobType.code, jobTypeId);
  }
  return jobTypes;
}

async function customersAndProperties(sql: postgres.Sql): Promise<Map<string, { customer: string; property: string }>> {
  const out = new Map<string, { customer: string; property: string }>();

  for (const c of CUSTOMERS) {
    const customerId = id(`cus:${c.key}`);
    const propertyId = id(`prop:${c.key}`);
    await sql`
      insert into public.customer
        (id, organization_id, type, name, email, phone, billing_address_line1, billing_address_line2,
         billing_city, billing_state, billing_postal_code, lead_source, payment_terms_days, tax_exempt)
      values (${customerId}, ${ORG}, ${c.type}, ${c.name}, ${c.email}, ${c.phone},
              ${c.address.line1}, ${c.address.line2 ?? null}, ${c.address.city}, ${c.address.state},
              ${c.address.postalCode}, ${c.leadSource ?? null}, ${String(c.paymentTerms ?? 0)}, ${c.taxExempt ?? false})
    `;
    await sql`
      insert into public.property
        (id, organization_id, address_line1, address_line2, city, state, postal_code, gate_code, has_dog, access_notes)
      values (${propertyId}, ${ORG}, ${c.address.line1}, ${c.address.line2 ?? null}, ${c.address.city},
              ${c.address.state}, ${c.address.postalCode}, ${c.gateCode ?? null}, ${c.hasDog ?? false},
              ${c.accessNotes ?? null})
    `;
    /**
     * The link is its own row rather than a column on the property, because a
     * property genuinely has several interested parties: an owner, a property
     * manager, and a tenant who is the one actually at the door.
     */
    await sql`
      insert into public.customer_property (id, organization_id, customer_id, property_id, role, is_primary)
      values (${id(`cp:${c.key}`)}, ${ORG}, ${customerId}, ${propertyId}, 'owner', true)
    `;
    out.set(c.key, { customer: customerId, property: propertyId });
  }
  return out;
}

async function work(
  sql: postgres.Sql,
  customers: Map<string, { customer: string; property: string }>,
  technicians: Map<string, string>,
  jobTypes: Map<string, string>,
): Promise<void> {
  let number = 1042;

  for (const spec of JOBS) {
    const link = customers.get(spec.customer);
    if (!link) throw new Error(`Seed job ${spec.key} names an unknown customer`);

    const jobId = id(`job:${spec.key}`);
    const visitId = id(`visit:${spec.key}`);
    const completed = spec.visitStatus === "completed";

    await sql`
      insert into public.job
        (id, organization_id, number, customer_id, property_id, job_type_id, status, summary,
         customer_complaint, total, completed_at)
      values (${jobId}, ${ORG}, ${number}, ${link.customer}, ${link.property},
              ${jobTypes.get(spec.type) ?? null}, ${completed ? "completed" : spec.status}, ${spec.summary},
              ${spec.complaint}, ${spec.total}, ${completed ? spec.end : null})
    `;

    await sql`
      insert into public.visit
        (id, organization_id, job_id, sequence, status, window_start, window_end,
         estimated_duration_minutes, location_id, dispatched_at, en_route_at, arrived_at, completed_at, technician_notes)
      values (${visitId}, ${ORG}, ${jobId}, 1, ${spec.visitStatus}, ${spec.start}, ${spec.end},
              ${spec.duration}, ${id("loc")},
              ${spec.tech ? spec.start : null},
              ${["en_route", "working", "completed"].includes(spec.visitStatus) ? spec.start : null},
              ${["working", "completed"].includes(spec.visitStatus) ? spec.start : null},
              ${completed ? spec.end : null},
              ${completed ? "Both systems within spec. Recommended filter change at next visit." : null})
    `;

    /**
     * The "on my way" notice, for the one visit that is actually en route.
     *
     * The tracking page counts down from this, so without it the customer
     * facing screen has nothing to show and the demo makes the most useful
     * thing the product does look like an empty card.
     */
    if (spec.visitStatus === "en_route") {
      const sent = new Date(Date.now() - 6 * 60_000);
      await sql`
        insert into public.arrival_notice (id, organization_id, visit_id, channel, sent_at, eta_minutes, delivered_at)
        values (${id(`notice:${spec.key}`)}, ${ORG}, ${visitId}, 'sms', ${sent}, 25, ${sent})
      `;
    }

    if (spec.tech) {
      const technicianId = technicians.get(spec.tech);
      if (!technicianId) throw new Error(`Seed job ${spec.key} names an unknown technician`);
      await sql`
        insert into public.visit_assignment (id, organization_id, visit_id, technician_id, is_lead)
        values (${id(`va:${spec.key}`)}, ${ORG}, ${visitId}, ${technicianId}, true)
      `;
    }
    number += 1;
  }

  await invoices(sql, customers);
}

/**
 * Receivables in three states, because an AR screen that only shows paid
 * invoices tells an owner nothing about whether they can make payroll.
 *
 * Note there is no "overdue" status, deliberately. Overdue is a fact about
 * today and a due date, not a state somebody has to remember to set. An
 * invoice that has to be marked overdue by a nightly job is an invoice that
 * is quietly not overdue whenever that job fails.
 */
